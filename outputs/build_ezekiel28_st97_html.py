def ruby(value):
    result = escape(value)
    pattern = re.compile("|".join(re.escape(k) for k in sorted(RUBY, key=len, reverse=True)))
    return pattern.sub(lambda m: f"<ruby>{m.group(0)}<rt>{RUBY[m.group(0)]}</rt></ruby>", result)


def ml(value):
    return "<br>".join(ruby(value).splitlines())


def ul(items, cls=""):
    attr = f' class="{cls}"' if cls else ""
    return f"<ul{attr}>" + "".join(f"<li>{ml(x)}</li>" for x in items) + "</ul>"


